#pragma once

#include <Arduino.h>  // 为了拿到核心定义的 RGB_BUILTIN 宏

// ============================================================
//  需要你确认 / 修改的配置，都集中在这个文件里
// ============================================================

// ---------- 学号 ----------
// 按下开发板上的 BOOT 键后，这串字符会通过蓝牙发给手机/PC
#define STUDENT_ID "8524035254"

// ---------- 蓝牙设备名 ----------
// 手机扫描蓝牙时看到的名字。把学号带上，答辩时一眼就能认出自己的板子。
// 注意：BLE 广播名建议不超过 20 个 ASCII 字符，太长会被截断。
#define BLE_DEVICE_NAME "ESP32S3-" STUDENT_ID

// ---------- 板载 RGB 灯 ----------
// ESP32-S3-DevKitC-1 板载一颗 WS2812 单总线彩灯，必须用核心自带的
// rgbLedWrite() 驱动，不能用 digitalWrite()。
// 引脚直接用核心的 RGB_BUILTIN 宏，ESP32-S3 上它就等于 GPIO48。
// 下面这层兜底只是防止个别板子的核心没定义这个宏。
//
// （引脚与驱动方式已对齐微信收到的参考工程 ESP32S3_Serial_StudentID，
//   那份工程在真实板子上跑通过）
#ifndef RGB_BUILTIN
#define RGB_BUILTIN 48
#endif

// ---------- 灯"开"时的颜色 (R, G, B，每个 0-255) ----------
// WS2812 全亮很刺眼，直接调分量值当亮度用即可，不需要额外的亮度参数。
// 参考工程用的是纯红 (255,0,0)；这里用柔和的绿色。
#define LED_ON_R 0
#define LED_ON_G 64
#define LED_ON_B 0

// ---------- 板载 BOOT 按键 ----------
// GPIO0 内部上拉，按下时为低电平
#define BUTTON_PIN 0

// 按键消抖时间(ms)：抖动的毛刺短于这个值会被忽略
#define BUTTON_DEBOUNCE_MS 50
